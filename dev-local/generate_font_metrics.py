#!/usr/bin/env python3
"""Regenerate font_metrics.h, the glyph sizes the e-ink emulator uses for the FreeSans fonts.

Reads the Adafruit GFX font headers from the Arduino libraries folder and writes only the
per-glyph metrics (width, height, xAdvance, xOffset, yOffset), so the emulator lays text out
exactly as the display library does.

    python3 dev-local/generate_font_metrics.py [path/to/Adafruit_GFX_Library/Fonts]
"""
import os
import re
import sys

FONTS = [
    ("FreeSans24pt7b", "FreeSans24"),
    ("FreeSansBold24pt7b", "FreeSansBold24"),
    ("FreeSans18pt7b", "FreeSans18"),
    ("FreeSansBold18pt7b", "FreeSansBold18"),
]

default_dir = os.path.expanduser("~/Documents/Arduino/libraries/Adafruit_GFX_Library/Fonts")
fonts_dir = sys.argv[1] if len(sys.argv) > 1 else default_dir
output = os.path.join(os.path.dirname(os.path.abspath(__file__)), "font_metrics.h")

lines = [
    "// Generated by generate_font_metrics.py from the Adafruit GFX FreeSans fonts: glyph metrics only.",
    "// Each row: width, height, xAdvance, xOffset, yOffset for ASCII 0x20..0x7E.",
    "#pragma once",
    "#include <cstdint>",
    "",
]
for header, name in FONTS:
    source = open(os.path.join(fonts_dir, header + ".h")).read()
    glyphs = re.search(r"GFXglyph \w+Glyphs\[\] PROGMEM = \{(.*?)\};", source, re.S).group(1)
    rows = re.findall(r"\{\s*\d+,\s*(\d+),\s*(\d+),\s*(\d+),\s*(-?\d+),\s*(-?\d+)\s*\}", glyphs)
    assert len(rows) == 95, (header, len(rows))
    lines.append("static const int16_t FONT_METRICS_%s[95][5] = {" % name)
    lines.extend("  {%s}," % ", ".join(row) for row in rows)
    lines.append("};")
    lines.append("")

with open(output, "w") as handle:
    handle.write("\n".join(lines))
print("wrote", output)
